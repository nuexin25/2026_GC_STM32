/* =========================================================================
 * [7] 任务调试：转盘阶段（bsp_task_dbg.c 的 TDBG_TRAY_PICK 用）
 * =========================================================================
 * 说明：以下参数服务于"任务点调试页"的转盘取料单点流程
 *       （协议 v2.0 §6.1：$RCP -> 对位 -> 观察位 -> $RZ -> 准备位 Q -> $CCG 轮询 -> 抓 -> 放车载）。
 *       全部机械臂动作编号本次填 0 = **未配置**：代码遇到 0 会打
 *       `[TDBG] arm act not configured` 并**跳过该动作继续**（保证流程先跑通）。 */

/* 等 $RCP 应答超时，单位 ms，默认 3000，可调 1000~10000。
 * 用途：小车停稳发 $RCP 后，等有效 $RCP,dx,dy 的最长时间；超时判 FAIL（停车 + 日志）。
 * 调法：树莓派识别慢就调大；调小可更快暴露"没回应"。 */
#define TRAY_RCP_TIMEOUT_MS      3000U

/* ★【2026-10-24 新增】转盘区"没看到转盘 -> 向右挪一段 -> 重新识别"兜底。
 * 背景：$RCP 回 (0,0) = 视觉没找到转盘（RPi_GetRcp()->valid=0），原地死等只会超时 FAIL；
 *       只要小车向右平移一小段换个视角，往往就能重新看到转盘。
 * 流程：TT_WAIT_RCP 等 TRAY_RCP_SHIFT_WAIT_MS 仍无有效数据 -> 右移 TRAY_RCP_SHIFT_MM
 *       -> 重发 $RCP 回到 TT_WAIT_RCP；最多右移 TRAY_RCP_SHIFT_MAX 次，用完才 FAIL。 */

/* 发 $RCP 后等多久仍无有效数据就触发一次右移，单位 ms，默认 800，可调 300~3000。
 * 调法：比树莓派"识别 + 回帧"慢一点点即可（太小会在正常识别前就乱挪）。 */
#define TRAY_RCP_SHIFT_WAIT_MS   800U

/* 每次右移的距离，单位 mm，默认 60，可调 30~150（正数；方向由 TRAY_RCP_SHIFT_SIGN 决定）。 */
#define TRAY_RCP_SHIFT_MM        60

/* 最多右移几次，默认 3（最多让开 180mm），可调 0~6；用完仍看不到 -> FAIL。 */
#define TRAY_RCP_SHIFT_MAX       3U

/* 单次右移的到位超时，单位 ms，默认 4000，可调 2000~8000；超时判 FAIL。 */
#define TRAY_RCP_SHIFT_TIMEOUT_MS 4000U

/* 右移方向符号：+1 = 车身右侧（默认，与 MEC_SIGN_VY 的"dy>0=右移"一致）；-1 = 取反。
 * 调法：**现场若看到车往左挪**，只把本宏改 -1，不要动逻辑。 */
#define TRAY_RCP_SHIFT_SIGN      (+1)

/* $RZ 的重发间隔，单位 ms，默认 150，可调 100~500。
 * 用途：`$RZ` 是**单次快照**（一问一答，树莓派只在收到请求时回一帧，且只反映那一瞬间的识别结果）。
 *       视觉端可能此刻还没识别出目标色（回 `$RZ,1,0,2,0,3,0`），
 *       所以**必须周期重发**，直到某一帧里出现目标色为止，而不是只发一次就判失败。
 * 调法：比树莓派"识别 + 回帧"耗时略大即可。 */
#define TRAY_RZ_POLL_MS          150U

/* ===================== ★【2026-10-24】转盘"计时推算"抓取 =====================
 * 新逻辑（取代原来的 $CCG 等目标色转到准备位）：
 *   ① 对位成功后连续发 $RZ，先锁一份**基准映射**（位号↔颜色，要求连续两帧一致才认）；
 *   ② 继续发 $RZ，一旦映射相对基准发生**完美循环移位**（且连续两帧一致）就认定
 *      "转盘转过了一步"，把那次变化的首次出现时刻记为 t0；
 *   ③ 第 1 件：直接用 t0 那帧里目标色所在的位号去抓（不推算）；
 *   ④ 第 2/3 件：**不再回观察位、不再对位**，位置 = 基准位号 + 转动步数（由 t0 到现在的时间算）。
 * 例：T=6000ms 时，6~12s 表示已经转了 1 步，12~18s 转了 2 步，依此类推。
 * 保险策略：每个 T 周期**前 TRAY_ROT_LEAD_MS（默认 2s）** 就地抓算出来的位号；
 *          **之后**提前去"算出来 +1"的下一个位号，**停在那里等料转到位**再抓
 *          （例：T=6s / LEAD=2s -> 6~8s 在 +1 位抓，8~12s 去 +2 位等到 12s 再抓）。 */

/* 转盘"转过一个位号"的周期，单位 ms，默认 6000，可调 2000~20000。
 * 调法：**现场用秒表量**"同一物料从 1 号位转到 2 号位"的时间，改成本值即可。
 *       这是推算的唯一时间基准，填错会整体偏位。 */
#define TRAY_ROT_PERIOD_MS       6000U

/* ★【2026-10-24】每个周期"就地抓"的窗口长度，单位 ms，默认 2000，可调 0~TRAY_ROT_PERIOD_MS。
 * 周期内已过时间 < 本值 -> 直接抓"推算出来的位号"；
 *              ≥ 本值 -> 提前去"推算出来的下一个位号"，停在那儿**等料转到位**再抓。
 * 调法：手臂过去越慢、越要提前 -> 调**小**（默认 2s = 后 4s 都在下一格等位）；
 *       就地抓的窗口想要更长 -> 调大；调大到接近周期就等于"不去下一格等"，保险性下降。 */
#define TRAY_ROT_LEAD_MS         2000U

/* 物料前进方向：+1 = 物料沿 1->2->3->1 走（默认）；-1 = 反向（1->3->2->1）。
 * 调法：**现场若发现推算位置总是差一位**，先确认周期，再翻本宏试一次。 */
#define TRAY_ROT_DIR             (+1)

/* 等"基准映射稳定"（连续两帧一致）的超时，单位 ms，默认 20000，可调 5000~40000。
 * 用途：对位成功起计时，本值内拿不到一份稳定的"位号↔颜色"就判 FAIL。
 * 调法：转盘一直在转、视觉偶尔漏识别时可以调大。 */
#define TRAY_RZ_BASE_TIMEOUT_MS  20000U

/* 等"映射发生变化"（= 抓到转动边沿）的超时，单位 ms，默认 20000，可调 5000~40000。
 * 用途：基准锁定后开始计时，本值内没等到"完美循环移位"就判 FAIL。
 * 调法：应大于一个转动周期（TRAY_ROT_PERIOD_MS），留 2~3 个周期最稳。 */
#define TRAY_RZ_EDGE_TIMEOUT_MS  20000U

/* 机械臂动作阶段的等待超时，单位 ms，默认 15000，可调 5000~30000。
 * 用途：转盘取料里每个机械臂动作（观察位 / 目标位 / 抓紧 / 放车载）从"启动"到"跑完"的上限；
 *       超时判 FAIL（停机器 + 日志，不卡死）。
 * 说明：**机械臂动作不再用"动作编号"，全部直接调 bsp_arm_action 的接口**
 *       （`ArmAct_GotoTtReady` / `ArmAct_GotoTtPos` / `ArmAct_Run(ARM_OP_*)`），
 *       动作组与标定值都在 bsp_arm_action.h。 */
#define TRAY_ARM_TIMEOUT_MS      15000U

/* ★【2026-10-24 用户要求】"舵盘(舵机3)转向太快，等手臂把物料松开、抬起来了再转舵盘，
 *   不要同时"——放料动作（含最后一步"电机6 抬回安全高"）**跑完之后**再等本值，
 *   才让舵盘转到下一个车载位号。单位 ms，默认 300，可调 0~1000。
 * 调法：现场若还觉得"抬臂和转舵盘挨太近"，加到 400~600；想完全跟手就调到 0。 */
