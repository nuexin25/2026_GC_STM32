/* =========================================================================
 * [0] 视觉对位数据源选择（Align() 的 target 参数取值）
 * -------------------------------------------------------------------------
 * 视觉端按"当前在哪个作业点"回不同路的像素偏移（见《树莓派通讯协议.md》v2.0）：
 *   ALIGN_TURNTABLE = 转盘**中心**偏移（$RCP，收到 $RCP,dx,dy）—— 原料区取料用；
 *   ALIGN_ROUGH     = 粗加工靶位圆环偏移（$SHOT）—— 粗加工区放/取用；
 *   ALIGN_FINE      = 暂存区/精加工靶位圆环偏移（$SHOT）—— 暂存区放/码垛用。
 * 对位实现见 bsp_align：转盘区走 Align_Start()（数据源 $RCP），
 * 打靶区走 Align_StartShot()（数据源 $SHOT）。
 * ========================================================================= */
typedef enum {
    ALIGN_TURNTABLE = 0,   /* 转盘 1 号位（原料区取料） */
    ALIGN_ROUGH,           /* 粗加工靶位（粗加工区）   */
    ALIGN_FINE             /* 精加工靶位（暂存区）     */
} AlignTarget_t;

