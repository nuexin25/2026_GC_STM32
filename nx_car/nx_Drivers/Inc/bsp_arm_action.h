/**
 ******************************************************************************
 * @file    bsp_arm_action.h
 * @brief   赛题抓取动作库（P9 用）：9 个位置的标定表 + 5 条固定执行流程
 * @author  nx_car
 * @date    2026-09-28
 ******************************************************************************
 * @note   【本模块解决什么问题】
 *         原来每个位置都要手抄一整段 `armSteps_xxx[]`（十几行、数值散落），
 *         加一个位置就要抄一遍，改一处要同步改几处。
 *         现在把"**动作流程**"和"**该位置走到的数值**"拆开：
 *           · 流程 = 固定的（见 .c 里的 5 个模板，顺序写死，不用动）；
 *           · 数值 = 标定出来的，全部集中在下面的 **ARM_CAL_LIST** 一张表里。
 *         以后**只改 ARM_CAL_LIST**，流程与逻辑代码一行都不用碰。
 *
 *         【四个参数是什么】（详见 bsp_arm.h 的坐标约定）
 *           M5 = 电机5 手臂左右转向位置（下发脉冲域，可正可负）
 *           M6 = 电机6 升降位置（下发脉冲域；**0 = 最高点，向下为负**）
 *           S1 = 舵机1 爪子前伸/缩回（0~1000；小 = 缩回，大 = 伸出）
 *           S2 = 舵机2 爪子抓紧/松开（0~1000；**小(≈100) = 抓紧，大(500~1000) = 松开**）
 *
 *         【为什么是 18 行而不是 9 行】
 *         转盘只有"抓取"，车载和靶子各有"抓取 + 放置"，第二批堆叠区只有"放置"，
 *         共 6 个动作 × 3 个位置 = 18 行。
 *         不能只写 9 行：同一个位置的 **S2 在抓取时要"夹紧"、放置时要"松开"**，
 *         两个值天然不同（靶子尤其明显）。车载两套的 S2 恰好都是"夹紧"，
 *         所以那两行的 S2 可以填同一个数 —— 但仍然要占两行。
 *
 *         【怎么用】（详见《赛题调参手册》）
 *           ArmAct_Run(ARM_OP_TT_PICK, 1);                          // 抓转盘1号位
 *           ArmAct_Run(ARM_OP_CAR_PLACE, 2);                        // 把料放到车载2号盘
 *           ArmAct_RunPair(ARM_OP_CAR_PICK, 2, ARM_OP_TGT_PLACE, 1);// 抓车载2号位→放靶子1号位
 *           主循环里调 ArmAct_Update()；用 ArmAct_IsBusy() 判断是否还在动。
 *
 *         【安全】标定表里任一项还是 ARM_UNSET -> **拒绝执行**并打日志，
 *         防止没标定就把机械臂按 0 位乱动。
 *
 *         硬约束：全部非阻塞（禁止 HAL_Delay）；日志禁 %f。
 ******************************************************************************
 */
